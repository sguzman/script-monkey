const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const dir = path.join(__dirname,"..");
const read = file => fs.readFileSync(path.join(dir,file),"utf8");
const manifest = JSON.parse(read("manifest.json"));
const worker = read("worker.js"), content = read("content.js");
test("narrow native messaging extension", () => {
  assert.equal(manifest.manifest_version,3);
  assert(manifest.permissions.includes("nativeMessaging"));
  assert.deepEqual(manifest.host_permissions,["https://chatgpt.com/*","https://chat.openai.com/*"]);
});
test("no head observation, polling of transcript or automatic YAML execution", () => {
  assert(!/document\.head/.test(content));
  assert(!/setInterval\s*\(/.test(content + worker));
  assert(!/window\.location\.reload/.test(content + worker));
  assert(content.includes('button.addEventListener("click"'));
  assert(worker.includes('message.type === "jobflick:validate"'));
});
test("tab ID generated by client and excluded from YAML", () => {
  assert(worker.includes("crypto.randomUUID()"));
  assert(worker.includes("origin_tab_id:origin"));
  assert(!content.includes("origin_tab_id"));
  assert(worker.includes("canonical(tab.url) !== record.conversation"));
});
test("durable tracking, no blind resubmission", () => {
  assert.equal((worker.match(/action:"submit_spec"/g) || []).length,1);
  assert(worker.includes('action:"inspect"'));
  assert(worker.includes('action:"show"'));
  assert(worker.includes("chrome.storage.local"));
  assert(worker.includes("periodInMinutes: 0.5"));
});

test("origin token prevents delivery into reused browser tab IDs", () => {
  assert(worker.includes('token !== record.origin'));
  assert(worker.includes('chrome.storage.session.get(key)'));
  assert(worker.includes('if (record.tab === id) delete jobs[jobId]'));
  assert(worker.indexOf('token !== record.origin') < worker.indexOf('action:"show"'));
});

test("bounded validator waits for capacity without dropping candidates", () => {
  assert(content.includes("const capacity = Math.max(0,4-activeChecks)"));
  assert(content.includes("dirty.delete(pre)"));
  assert(!content.includes("dirty.clear();\n    for (const pre of batch)"));
  assert(content.includes("if (dirty.size && !scheduled) scheduled = setTimeout(drain,250)"));
});
